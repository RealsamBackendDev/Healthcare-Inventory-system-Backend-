const approveThresholdRequest = async ({ actor, scope, approvalId, comment }) => {
  const localGovernmentId = requireLocalGovernmentScope(scope);

  const claim = await withTransaction(async (client) => {
    const locked = await repository.lockApproval(client, localGovernmentId, approvalId);
    if (!locked) {
      throw new NotFoundError('Approval request was not found');
    }
    if (locked.status !== 'pending') {
      throw new ConflictError('This approval request has already been decided', 'APPROVAL_ALREADY_DECIDED');
    }
    if (locked.requested_by === actor.id) {
      throw new ForbiddenError('A second officer must approve this request', 'SECOND_APPROVAL_REQUIRED');
    }
    if (locked.expires_at && new Date(locked.expires_at).getTime() < Date.now()) {
      return { expired: true };
    }
    return { approval: await repository.setApprovalStatus(client, { approvalId, status: 'processing' }) };
  });

  if (claim.expired) {
    await withTransaction((client) =>
      repository.setApprovalStatus(client, {
        approvalId,
        status: 'expired',
        decidedById: actor.id,
        decidedByName: actor.fullName,
        reason: 'The approval window expired'
      })
    );
    throw new ConflictError('The approval window for this request has expired', 'APPROVAL_EXPIRED');
  }

  const approval = claim.approval;

  let reference;
  try {
    if (approval.approval_type === 'receipt') {
      const receipt = await postReceipt({ actor, scope, payload: approval.payload });
      reference = { type: 'lg_receipt', id: receipt.id, label: receipt.receiptNumber };
    } else {
      const dispatch = await postDispatch({
        actor,
        scope,
        requisitionId: approval.payload.requisitionId,
        payload: approval.payload
      });
      reference = { type: 'lg_dispatch', id: dispatch.id, label: dispatch.dispatchNumber };
    }
  } catch (error) {
    await withTransaction((client) => repository.setApprovalStatus(client, { approvalId, status: 'pending' }));
    throw error;
  }

  const mapped = await withTransaction(async (client) => {
    const updated = await repository.setApprovalStatus(client, {
      approvalId,
      status: 'approved',
      decidedById: actor.id,
      decidedByName: actor.fullName,
      reason: comment || null,
      referenceType: reference.type,
      referenceId: reference.id
    });

    await recordAudit(client, {
      ...auditContext(scope),
      actor,
      action: 'threshold.approval_granted',
      entityType: 'lg_threshold_approval',
      entityId: approvalId,
      summary: `Approved ${approval.approval_type} request as ${reference.label}`,
      newValues: { reference }
    });

    return mapApproval(updated);
  });

  return { approval: mapped, reference };
};

