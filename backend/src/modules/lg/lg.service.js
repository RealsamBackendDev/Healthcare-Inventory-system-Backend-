const postReceipt = async ({ actor, scope, payload }) => {
  const localGovernmentId = requireLocalGovernmentScope(scope);
  const warehouse = await getWarehouse(localGovernmentId);

  const items = payload.items.map((item) => ({
    drugId: item.drugId,
    batchNumber: item.batchNumber.trim(),
    expiryDate: item.expiryDate || null,
    quantity: roundQuantity(Number(item.quantity)),
    unitCost: item.unitCost === undefined || item.unitCost === null ? null : Number(item.unitCost)
  }));

  const seen = new Set();
  items.forEach((item, index) => {
    const key = `${item.drugId}::${item.batchNumber.toLowerCase()}`;
    if (seen.has(key)) {
      throw new ValidationError('Each batch can only appear once in a receipt', [
        { field: `items.${index}.batchNumber`, message: 'This batch is already on the receipt' }
      ]);
    }
    seen.add(key);
  });

  const drugs = await repository.findDrugs(
    localGovernmentId,
    [...new Set(items.map((item) => item.drugId))]
  );
  const drugsById = new Map(drugs.map((drug) => [drug.id, drug]));
  items.forEach((item, index) => {
    const drug = drugsById.get(item.drugId);
    if (!drug || !drug.is_active) {
      throw new ValidationError('One or more items are not in the local government catalogue', [
        { field: `items.${index}.drugId`, message: 'Drug is not available in this local government' }
      ]);
    }
  });

  const totalQuantity = roundQuantity(items.reduce((total, item) => total + item.quantity, 0));
  const totalValue = Number(
    items
      .reduce((total, item) => total + (item.unitCost ? item.quantity * item.unitCost : 0), 0)
      .toFixed(2)
  );
  const thresholds = await getThresholds(localGovernmentId);

  if (
    !payload.thresholdApproved &&
    (totalQuantity > thresholds.receiptQuantity ||
      (thresholds.receiptValue > 0 && totalValue > thresholds.receiptValue))
  ) {
    throw new ConflictError(
      `This receipt is above the ${thresholds.receiptQuantity} unit / ${thresholds.receiptValue} value threshold and needs confirmation`,
      'THRESHOLD_CONFIRMATION_REQUIRED'
    );
  }

  const result = await withTransaction(async (client) => {
    const receipt = await repository.insertReceipt(client, {
      localGovernmentId,
      receiptNumber: buildNumber('WRC'),
      supplierName: payload.supplierName,
      supplierReference: payload.supplierReference,
      notes: payload.notes,
      actorId: actor.id,
      actorName: actor.fullName
    });

    for (const item of items) {
      const batch = await repository.insertWarehouseBatch(client, {
        localGovernmentId,
        warehouseId: warehouse.id,
        drugId: item.drugId,
        batchNumber: item.batchNumber,
        expiryDate: item.expiryDate,
        quantity: item.quantity,
        unitCost: item.unitCost,
        supplierReference: payload.supplierReference
      });

      await repository.insertReceiptItem(client, {
        receiptId: receipt.id,
        drugId: item.drugId,
        batchId: batch.id,
        batchNumber: item.batchNumber,
        expiryDate: item.expiryDate,
        quantity: item.quantity,
        unitCost: item.unitCost
      });
    }

    await recordAudit(client, {
      ...auditContext(scope),
      actor,
      action: 'warehouse.received',
      entityType: 'lg_receipt',
      entityId: receipt.id,
      summary: `Received ${items.length} batch(es) into ${warehouse.name} (${receipt.receipt_number})`,
      newValues: { items, totalQuantity, totalValue }
    });

    return receipt;
  });

  return {
    id: result.id,
    receiptNumber: result.receipt_number,
    receivedAt: result.received_at,
    itemCount: items.length,
    totalQuantity,
    totalValue
  };
};

