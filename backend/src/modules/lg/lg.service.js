const createConsolidation = async ({ actor, scope, payload }) => {
  const localGovernmentId = requireLocalGovernmentScope(scope);
  const preview = await buildConsolidationPreview(localGovernmentId, payload.requisitionIds);

  if (preview.items.length === 0) {
    throw new ValidationError('These requests have no items to consolidate', [
      { field: 'requisitionIds', message: 'Nothing to consolidate' }
    ]);
  }

  try {
    const created = await withTransaction(async (client) => {
      const consolidation = await repository.insertConsolidation(client, {
        localGovernmentId,
        reference: buildNumber('CNS'),
        notes: payload.notes || null,
        itemCount: preview.totals.itemCount,
        sourceCount: preview.totals.sourceCount,
        totalQuantity: preview.totals.requestedQuantity,
        gapQuantity: preview.totals.gapQuantity,
        actorId: actor.id,
        actorName: actor.fullName
      });

      for (const source of preview.sources) {
        await repository.insertConsolidationSource(client, { consolidationId: consolidation.id, ...source });
      }
      for (const item of preview.items) {
        await repository.insertConsolidationItem(client, { consolidationId: consolidation.id, ...item });
      }

      await recordAudit(client, {
        ...auditContext(scope),
        actor,
        action: 'consolidation.created',
        entityType: 'lg_consolidation',
        entityId: consolidation.id,
        summary: `Consolidated ${preview.totals.sourceCount} request(s) into ${consolidation.reference}`,
        newValues: preview.totals
      });

      return consolidation;
    });

    return getConsolidation({ scope, consolidationId: created.id });
  } catch (error) {
    if (error.code === '23505') {
      throw new ConflictError('One of these requests was just consolidated by someone else', 'ALREADY_CONSOLIDATED');
    }
    throw error;
  }
};

