const createFacilityTransfer = async ({ actor, scope, payload }) => {
  const localGovernmentId = requireLocalGovernmentScope(scope);

  if (payload.fromCentreId === payload.toCentreId) {
    throw new ValidationError('Choose two different facilities', [
      { field: 'toCentreId', message: 'The receiving facility must be different' }
    ]);
  }

  const [from, to] = await Promise.all([
    repository.findFacilityCentre(localGovernmentId, payload.fromCentreId),
    repository.findFacilityCentre(localGovernmentId, payload.toCentreId)
  ]);
  if (!from || !to) {
    throw new NotFoundError('One of the facilities was not found in this local government');
  }

  const fromLocation = await repository.findFacilityLocation(from.id);
  const toLocation = await repository.findFacilityLocation(to.id);
  if (!fromLocation || !toLocation) {
    throw new NotFoundError('A facility is missing an active store location', 'FACILITY_LOCATION_MISSING');
  }

  const wanted = new Map();
  payload.items.forEach((item, index) => {
    const quantity = roundQuantity(Number(item.quantity));
    if (!isPositive(quantity)) {
      throw new ValidationError('Each line needs a quantity above zero', [
        { field: `items.${index}.quantity`, message: 'Quantity must be greater than zero' }
      ]);
    }
    wanted.set(item.drugId, roundQuantity((wanted.get(item.drugId) || 0) + quantity));
  });

  if (wanted.size === 0) {
    throw new ValidationError('Add at least one drug to transfer', [
      { field: 'items', message: 'Add at least one drug' }
    ]);
  }

  const drugs = await repository.findDrugs(localGovernmentId, [...wanted.keys()]);
  const drugsById = new Map(drugs.map((drug) => [drug.id, drug]));
  for (const drugId of wanted.keys()) {
    const drug = drugsById.get(drugId);
    if (!drug || !drug.is_active) {
      throw new ValidationError('One or more drugs are not in the local government catalogue', [
        { field: 'items', message: 'Drug is not available in this local government' }
      ]);
    }
  }

  const created = await withTransaction(async (client) => {
    const lines = [];

    for (const [drugId, quantity] of wanted.entries()) {
      const drug = drugsById.get(drugId);
      const batches = await repository.lockAvailableBatches(client, fromLocation.id, drugId);
      const { allocations, remaining } = allocateBatches(batches, quantity);

      if (remaining > QUANTITY_EPSILON) {
        throw new ConflictError(
          `Not enough ${drug.name} at ${from.name} (short by ${roundQuantity(remaining)})`,
          'INSUFFICIENT_FACILITY_STOCK'
        );
      }

      for (const allocation of allocations) {
        const updated = await repository.decrementBatch(client, allocation.batch.id, allocation.quantity);
        if (!updated) {
          throw new ConflictError('Stock changed while transferring, try again', 'TRANSFER_STOCK_CHANGED');
        }
        lines.push({
          drugId,
          sourceBatchId: allocation.batch.id,
          batchNumber: allocation.batch.batch_number,
          expiryDate: allocation.batch.expiry_date,
          quantity: allocation.quantity,
          unitCost: allocation.batch.unit_cost
        });
      }
    }

    const totalQuantity = roundQuantity(lines.reduce((total, line) => total + line.quantity, 0));

    const transfer = await repository.insertFacilityTransfer(client, {
      localGovernmentId,
      transferNumber: buildNumber('TRF'),
      fromCentreId: from.id,
      fromCentreName: from.name,
      toCentreId: to.id,
      toCentreName: to.name,
      notes: payload.notes || null,
      itemCount: wanted.size,
      totalQuantity,
      actorId: actor.id,
      actorName: actor.fullName
    });

    for (const line of lines) {
      await repository.insertFacilityTransferItem(client, { transferId: transfer.id, ...line });
      await repository.insertTransferOutMovement(client, {
        healthcareCentreId: from.id,
        drugId: line.drugId,
        batchId: line.sourceBatchId,
        quantity: -line.quantity,
        reason: `Transfer ${transfer.transfer_number} to ${to.name}`,
        actorId: actor.id,
        actorName: actor.fullName,
        sourceReference: transfer.transfer_number
      });
    }

    await recordAudit(client, {
      ...auditContext(scope),
      actor,
      action: 'facility_transfer.created',
      entityType: 'facility_transfer',
      entityId: transfer.id,
      summary: `Transferred ${totalQuantity} units from ${from.name} to ${to.name}`,
      newValues: { itemCount: wanted.size, totalQuantity }
    });

    return transfer;
  });

  return getFacilityTransfer({ scope, transferId: created.id });
};

