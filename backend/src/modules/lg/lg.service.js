const requireLocalGovernmentScope = (scope) => {
  if (!scope || scope.scopeType !== 'local_government' || !scope.localGovernmentId) {
    throw new ForbiddenError('This screen is only available to local government accounts', 'LOCAL_GOVERNMENT_ONLY');
  }
  return scope.localGovernmentId;
};

const buildNumber = (prefix) => {
  const date = todayIsoDate().replace(/-/g, '');
  return `${prefix}-${date}-${crypto.randomBytes(3).toString('hex').toUpperCase()}`;
};

const auditContext = (scope) => ({
  localGovernmentId: scope.localGovernmentId,
  actorRoleCode: scope.roleCode,
  actorScopeType: scope.scopeType
});

const getThresholds = async (localGovernmentId) => {
  const settings = await getLocalGovernmentSettingsMap(null, localGovernmentId);
  return {
    receiptQuantity: Number.parseFloat(settings[SETTING_KEYS.LG_RECEIPT_QUANTITY_THRESHOLD]) || 0,
    receiptValue: Number.parseFloat(settings[SETTING_KEYS.LG_RECEIPT_VALUE_THRESHOLD]) || 0,
    dispatchQuantity: Number.parseFloat(settings[SETTING_KEYS.LG_DISPATCH_QUANTITY_THRESHOLD]) || 0
  };
};

