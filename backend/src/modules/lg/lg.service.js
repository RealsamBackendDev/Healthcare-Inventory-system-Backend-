const buildConsolidationPreview = async (localGovernmentId, requisitionIds) => {
  const warehouse = await getWarehouse(localGovernmentId);
  const uniqueIds = [...new Set(requisitionIds)];

  const [requisitions, alreadyUsed, demandRows] = await Promise.all([
    repository.findRequisitionsForConsolidation(localGovernmentId, uniqueIds),
    repository.findConsolidatedRequisitions(uniqueIds),
    repository.consolidationDemandRows(localGovernmentId, warehouse.id, uniqueIds)
  ]);

  if (requisitions.length !== uniqueIds.length) {
    throw new ValidationError('One or more requests are not in this local government', [
      { field: 'requisitionIds', message: 'Request was not found in this local government' }
    ]);
  }

  const notApproved = requisitions.filter((row) => row.status !== REQUISITION_STATUS.APPROVED);
  if (notApproved.length > 0) {
    throw new ConflictError(
      `Only approved requests can be consolidated. ${notApproved
        .map((row) => row.requisition_number)
        .join(', ')} not approved`,
      'REQUISITION_NOT_APPROVED'
    );
  }

  if (alreadyUsed.length > 0) {
    throw new ConflictError(
      `Requests already consolidated: ${alreadyUsed
        .map((row) => `${row.reference} (${row.status})`)
        .join(', ')}`,
      'ALREADY_CONSOLIDATED'
    );
  }

  const items = demandRows.map((row) => {
    const requestedQuantity = roundQuantity(Number(row.requested_quantity));
    const warehouseQuantity = roundQuantity(Number(row.warehouse_quantity));
    return {
      drugId: row.drug_id,
      code: row.code,
      name: row.name,
      unitOfMeasure: row.unit_of_measure,
      requestedQuantity,
      warehouseQuantity,
      gapQuantity: roundQuantity(Math.max(0, requestedQuantity - warehouseQuantity))
    };
  });

  const sources = requisitions.map((row) => ({
    requisitionId: row.id,
    requisitionNumber: row.requisition_number,
    healthcareCentreId: row.healthcare_centre_id,
    centreName: row.centre_name,
    requestedQuantity: roundQuantity(Number(row.total_quantity))
  }));

  const totals = {
    itemCount: items.length,
    sourceCount: sources.length,
    requestedQuantity: roundQuantity(items.reduce((total, item) => total + item.requestedQuantity, 0)),
    warehouseQuantity: roundQuantity(items.reduce((total, item) => total + item.warehouseQuantity, 0)),
    gapQuantity: roundQuantity(items.reduce((total, item) => total + item.gapQuantity, 0))
  };

  return { warehouse, sources, items, totals };
};

