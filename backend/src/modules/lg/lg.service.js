const cancelFacilityTransfer = async ({ actor, scope, transferId, reason }) => {
  const localGovernmentId = requireLocalGovernmentScope(scope);

  await withTransaction(async (client) => {
    const locked = await repository.lockFacilityTransfer(client, transferId);
    if (!locked || locked.local_government_id !== localGovernmentId) {
      throw new NotFoundError('Transfer was not found');
    }
    if (locked.status !== 'in_transit') {
      throw new ConflictError('Only a transfer still in transit can be cancelled', 'TRANSFER_NOT_CANCELLABLE');
    }

    const items = await repository.listFacilityTransferItems(transferId);
    for (const item of items) {
      if (!item.source_batch_id) {
        continue;
      }
      await repository.incrementBatch(client, item.source_batch_id, Number(item.quantity));
      await repository.insertTransferMovement(client, {
        healthcareCentreId: locked.from_healthcare_centre_id,
        drugId: item.drug_id,
        batchId: item.source_batch_id,
        quantity: Number(item.quantity),
        reason: `Transfer ${locked.transfer_number} cancelled`,
        actorId: actor.id,
        actorName: actor.fullName,
        sourceReference: locked.transfer_number
      });
    }

    await repository.updateFacilityTransferStatus(client, {
      transferId,
      status: 'cancelled',
      actorId: actor.id,
      actorName: actor.fullName,
      reason
    });

    await recordAudit(client, {
      ...auditContext(scope),
      actor,
      action: 'facility_transfer.cancelled',
      entityType: 'facility_transfer',
      entityId: transferId,
      summary: `Cancelled ${locked.transfer_number}`,
      reason
    });
  });

  return getFacilityTransfer({ scope, transferId });
};

