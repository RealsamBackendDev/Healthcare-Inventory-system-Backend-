const receiveFacilityTransfer = async ({ actor, scope, transferId, note }) => {
  const healthcareCentreId = scope.healthcareCentreId;
  if (!healthcareCentreId) {
    throw new ForbiddenError('This action needs a healthcare centre account', 'FACILITY_ONLY');
  }

  const location = await repository.findFacilityLocation(healthcareCentreId);
  if (!location) {
    throw new NotFoundError('This healthcare centre has no active store location');
  }

  await withTransaction(async (client) => {
    const locked = await repository.lockFacilityTransfer(client, transferId);
    if (!locked || locked.to_healthcare_centre_id !== healthcareCentreId) {
      throw new NotFoundError('Transfer was not found for this facility');
    }
    if (locked.status !== 'in_transit') {
      throw new ConflictError('This transfer has already been closed', 'TRANSFER_ALREADY_CLOSED');
    }

    const items = await repository.listFacilityTransferItems(transferId);
    for (const item of items) {
      const batch = await repository.insertFacilityBatch(client, {
        healthcareCentreId,
        localGovernmentId: location.local_government_id,
        stockLocationId: location.id,
        drugId: item.drug_id,
        batchNumber: item.batch_number,
        expiryDate: item.expiry_date,
        quantity: Number(item.quantity),
        unitCost: item.unit_cost,
        supplierReference: locked.transfer_number
      });

      await repository.insertTransferMovement(client, {
        healthcareCentreId,
        drugId: item.drug_id,
        batchId: batch.id,
        quantity: Number(item.quantity),
        reason: note || `Transfer ${locked.transfer_number} from ${locked.from_centre_name}`,
        actorId: actor.id,
        actorName: actor.fullName,
        sourceReference: locked.transfer_number
      });
    }

    await repository.updateFacilityTransferStatus(client, {
      transferId,
      status: 'received',
      actorId: actor.id,
      actorName: actor.fullName,
      note
    });

    await recordAudit(client, {
      healthcareCentreId,
      localGovernmentId: location.local_government_id,
      actor,
      actorRoleCode: scope.roleCode,
      actorScopeType: scope.scopeType,
      action: 'facility_transfer.received',
      entityType: 'facility_transfer',
      entityId: transferId,
      summary: `Confirmed transfer ${locked.transfer_number} from ${locked.from_centre_name}`,
      newValues: { itemCount: items.length }
    });
  });

  return getIncomingFacilityTransfer({ scope, transferId });
};

