const getRequisitionDetail = async ({ scope, requisitionId }) => {
  const localGovernmentId = requireLocalGovernmentScope(scope);
  const requisition = await repository.findRequisition(localGovernmentId, requisitionId);
  if (!requisition) {
    throw new NotFoundError('Requisition was not found in this local government');
  }

  const warehouse = await getWarehouse(localGovernmentId);
  const [items, events, dispatch] = await Promise.all([
    repository.listRequisitionItems(requisitionId),
    repository.listRequisitionEvents(requisitionId),
    repository.findDeliveryForRequisition(requisition.healthcare_centre_id, requisitionId)
  ]);

  const availability = {};
  for (const item of items) {
    const batches = await repository.warehouseBatches({ warehouseId: warehouse.id, drugId: item.drug_id });
    availability[item.drug_id] = roundQuantity(
      batches.reduce((total, batch) => total + Number(batch.quantity), 0)
    );
  }

  const mappedItems = items.map((item) => ({
    ...mapRequisitionItem(item),
    warehouseQuantity: availability[item.drug_id] || 0
  }));

  let dispatchDetail = null;
  if (dispatch) {
    const dispatchItems = await repository.listDispatchItems(dispatch.id);
    dispatchDetail = { ...mapDispatch(dispatch), items: dispatchItems.map(mapDispatchItem) };
  }

  return {
    requisition: mapRequisitionRow({
      ...requisition,
      item_count: mappedItems.length,
      total_quantity: mappedItems.reduce((total, item) => total + item.requestedQuantity, 0)
    }),
    items: mappedItems,
    events: events.map(mapEvent),
    dispatch: dispatchDetail
  };
};

const reviewRequisition = async ({ actor, scope, requisitionId, decision, comment, reason, items }) => {
  const localGovernmentId = requireLocalGovernmentScope(scope);

  return withTransaction(async (client) => {
    const requisition = await repository.lockRequisition(client, localGovernmentId, requisitionId);
    if (!requisition) {
      throw new NotFoundError('Requisition was not found in this local government');
    }
    if (requisition.status !== REQUISITION_STATUS.PENDING_APPROVAL) {
      throw new ConflictError('Only requisitions pending approval can be reviewed', 'REQUISITION_NOT_PENDING');
    }
    if (requisition.created_by === actor.id) {
      throw new ForbiddenError('You cannot review a requisition you created', 'SELF_APPROVAL_DENIED');
    }

    const approved = decision === 'approved';

    if (approved && Array.isArray(items) && items.length > 0) {
      const currentItems = await repository.listRequisitionItems(requisitionId);
      const byDrug = new Map(currentItems.map((item) => [item.drug_id, item]));
      const updates = [];

      for (const entry of items) {
        const item = byDrug.get(entry.drugId);
        if (!item) {
          throw new ValidationError('Only drugs on the requisition can be approved', [
            { field: 'items.drugId', message: 'This drug is not on the requisition' }
          ]);
        }
        const quantity = roundQuantity(Number(entry.approvedQuantity));
        if (!Number.isFinite(quantity) || quantity < 0) {
          throw new ValidationError('Approved quantities cannot be negative', [
            { field: 'items.approvedQuantity', message: 'Enter zero or more' }
          ]);
        }
        if (quantity > Number(item.requested_quantity) + QUANTITY_EPSILON) {
          throw new ValidationError('Approved quantity cannot exceed the requested quantity', [
            { field: 'items.approvedQuantity', message: 'Lower it to the requested amount or below' }
          ]);
        }
        updates.push({ drugId: entry.drugId, approvedQuantity: quantity });
      }

      const totalApproved = currentItems.reduce((total, item) => {
        const update = updates.find((entry) => entry.drugId === item.drug_id);
        return total + (update ? update.approvedQuantity : Number(item.requested_quantity));
      }, 0);

      if (totalApproved <= QUANTITY_EPSILON) {
        throw new ValidationError('Approve at least one unit, or reject the requisition instead', [
          { field: 'items', message: 'Every approved quantity is zero' }
        ]);
      }

      await repository.updateApprovedQuantities(client, { requisitionId, items: updates });
    }
    await repository.markReviewed(client, {
      localGovernmentId,
      requisitionId,
      status: approved ? REQUISITION_STATUS.APPROVED : REQUISITION_STATUS.REJECTED,
      actorId: actor.id,
      actorName: actor.fullName,
      reason: approved ? comment : reason
    });

    await repository.insertRequisitionEvent(client, {
      requisitionId,
      eventType: approved ? 'lg_approved' : 'lg_rejected',
      actorId: actor.id,
      actorName: actor.fullName,
      comment: approved ? comment || 'Approved by the local government' : reason
    });

    await recordAudit(client, {
      ...auditContext(scope),
      actor,
      action: approved ? 'requisition.lg_approved' : 'requisition.lg_rejected',
      entityType: 'requisition',
      entityId: requisitionId,
      summary: `${approved ? 'Approved' : 'Rejected'} requisition ${requisition.requisition_number} from ${requisition.centre_name}`,
      previousValues: { status: requisition.status },
      newValues: { status: approved ? REQUISITION_STATUS.APPROVED : REQUISITION_STATUS.REJECTED },
      reason: approved ? comment || null : reason
    });

    return getRequisitionDetail({ scope, requisitionId });
  });
};

const buildDispatchQuantities = (requisitionItems, payloadItems) => {
  const allowances = new Map();
  for (const item of requisitionItems) {
    const remaining = roundQuantity(
      Number(item.approved_quantity) - Number(item.dispatched_quantity || 0) + Number(item.missing_quantity || 0)
    );
    if (remaining > QUANTITY_EPSILON) {
      allowances.set(item.drug_id, remaining);
    }
  }

  if (!payloadItems || payloadItems.length === 0) {
    return [...allowances.entries()].map(([drugId, quantity]) => ({ drugId, quantity }));
  }

  const supplied = new Map();
  for (const entry of payloadItems) {
    const available = allowances.get(entry.drugId);
    if (available === undefined) {
      throw new ValidationError('This drug has nothing left to dispatch on this requisition', [
        { field: 'items.drugId', message: 'It is either not approved or already delivered' }
      ]);
    }
    const quantity = roundQuantity(Number(entry.quantity));
    if (!isPositive(quantity) || quantity > available + QUANTITY_EPSILON) {
      throw new ValidationError(
        'Dispatched quantity must be more than zero and no more than the approved quantity still outstanding',
        [{ field: 'items.quantity', message: 'Check the quantity against what is still owed' }]
      );
    }
    supplied.set(entry.drugId, quantity);
  }
  return [...supplied.entries()].map(([drugId, quantity]) => ({ drugId, quantity }));
};

const postDispatch = async ({ actor, scope, requisitionId, payload }) => {
  const localGovernmentId = requireLocalGovernmentScope(scope);
  const warehouse = await getWarehouse(localGovernmentId);

  const dispatchId = await withTransaction(async (client) => {
    const requisition = await repository.lockRequisition(client, localGovernmentId, requisitionId);
    if (!requisition) {
      throw new NotFoundError('Requisition was not found in this local government');
    }
    if (requisition.status !== REQUISITION_STATUS.APPROVED) {
      throw new ConflictError('Only approved requisitions can be dispatched', 'REQUISITION_NOT_APPROVED');
    }

    const items = await repository.listRequisitionItems(requisitionId);
    const quantities = buildDispatchQuantities(items, payload.items);

    if (quantities.length === 0) {
      throw new ConflictError(
        'Everything approved on this requisition has already been dispatched',
        'NOTHING_TO_DISPATCH'
      );
    }

    const totalQuantity = roundQuantity(quantities.reduce((total, item) => total + item.quantity, 0));
    const thresholds = await getThresholds(localGovernmentId);

    if (!payload.thresholdApproved && thresholds.dispatchQuantity > 0 && totalQuantity > thresholds.dispatchQuantity) {
      throw new ConflictError(
        `This dispatch is above the ${thresholds.dispatchQuantity} unit threshold and needs confirmation`,
        'THRESHOLD_CONFIRMATION_REQUIRED'
      );
    }

    const drugs = await repository.findDrugs(localGovernmentId, quantities.map((item) => item.drugId));
    const drugsById = new Map(drugs.map((drug) => [drug.id, drug]));

    const dispatch = await repository.insertDispatch(client, {
      localGovernmentId,
      requisitionId,
      healthcareCentreId: requisition.healthcare_centre_id,
      dispatchNumber: buildNumber('DSP'),
      notes: payload.notes,
      actorId: actor.id,
      actorName: actor.fullName
    });

    for (const requested of quantities) {
      let remaining = requested.quantity;
      const batches = await repository.lockAvailableBatches(client, warehouse.id, requested.drugId);

      for (const batch of batches) {
        if (remaining <= QUANTITY_EPSILON) break;
        const take = Math.min(remaining, Number(batch.quantity));
        const updated = await repository.decrementBatch(client, batch.id, take);
        if (!updated) {
          throw new ConflictError('Warehouse stock changed while dispatching, please try again', 'STOCK_CHANGED');
        }
        await repository.insertDispatchItem(client, {
          dispatchId: dispatch.id,
          drugId: requested.drugId,
          batchId: batch.id,
          batchNumber: batch.batch_number,
          expiryDate: batch.expiry_date,
          quantity: take,
          unitCost: batch.unit_cost
        });
        remaining = roundQuantity(remaining - take);
      }

      if (remaining > QUANTITY_EPSILON) {
        const drug = drugsById.get(requested.drugId);
        throw new ConflictError(
          `The warehouse does not have enough ${drug ? drug.name : 'stock'} for this dispatch`,
          'INSUFFICIENT_WAREHOUSE_STOCK'
        );
      }
    }

    await repository.insertRequisitionEvent(client, {
      requisitionId,
      eventType: 'dispatched',
      actorId: actor.id,
      actorName: actor.fullName,
      comment: payload.notes || `Dispatched as ${dispatch.dispatch_number}`
    });

    await recordAudit(client, {
      ...auditContext(scope),
      actor,
      action: 'dispatch.posted',
      entityType: 'lg_dispatch',
      entityId: dispatch.id,
      summary: `Dispatched ${dispatch.dispatch_number} to ${requisition.centre_name}`,
      newValues: { totalQuantity }
    });

    return dispatch.id;
  });

  return getDispatchDetail({ scope, dispatchId });
};

